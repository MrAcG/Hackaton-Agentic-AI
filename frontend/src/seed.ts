import type { ChatMessage, Snapshot, WorkNote } from "./types";

function at(minutesAgo: number): string {
  return new Date(Date.now() - minutesAgo * 60_000).toISOString();
}

function note(
  ticketId: string,
  id: string,
  author: string,
  authorType: WorkNote["author_type"],
  body: string,
  createdAt: string,
): WorkNote {
  return { id, ticket_id: ticketId, author, author_type: authorType, body, created_at: createdAt };
}

function message(
  ticketId: string,
  id: string,
  role: ChatMessage["role"],
  author: string,
  body: string,
  createdAt: string,
): ChatMessage {
  return { id, ticket_id: ticketId, role, author, body, created_at: createdAt };
}

